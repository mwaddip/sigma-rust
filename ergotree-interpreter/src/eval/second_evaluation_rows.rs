/// A run: the row's name in the round's row set, the tree's bytes, the activated version, what
/// the jars answer (`REFUSED`: the tree is refused at parse; `ERR`: the reduction fails; or the
/// proposition it reduces to) and the reduction's block cost
type Row = (&'static str, &'static str, i8, &'static str, u64);

/// A context with no variable, no cost yet and no cost limit. No row reads anything else of it
fn context(activated: i8) -> Context<'static> {
    let mut ctx = force_any_val::<Context>();
    ctx.extension = Box::leak(Box::new(ContextExtension::empty()));
    ctx.activated_script_version_byte = activated;
    ctx.jit_cost.set(0);
    ctx.jit_cost_limit = None;
    ctx
}

/// What the fork gives for a tree on the node's path, and the cost of the reduction
fn reduce_row(tree: &str, activated: i8) -> (String, u64) {
    let bytes = base16::decode(tree.as_bytes()).unwrap();
    let parsed = from_bytes(&bytes).with_versions(
        ErgoTreeVersion::from(activated as u8),
        ErgoTreeVersion::V3,
        ErgoTree::sigma_parse,
    );
    let Ok(tree) = parsed else {
        return ("REFUSED".into(), 0);
    };
    match reduce_to_crypto(&tree, &context(activated)) {
        Ok(r) if r.sigma_prop == SigmaBoolean::TrivialProp(true) => ("TrueProp".into(), r.cost),
        Ok(r) if r.sigma_prop == SigmaBoolean::TrivialProp(false) => ("FalseProp".into(), r.cost),
        Ok(r) => (format!("another proposition: {:?}", r.sigma_prop), r.cost),
        Err(_) => ("ERR".into(), 0),
    }
}

fn check(rows: &[Row]) {
    let mut wrongs = Vec::new();
    for (name, tree, activated, expected, cost) in rows {
        let (got, at) = reduce_row(tree, *activated);
        if got != *expected || at != *cost {
            wrongs.push(format!(
                "{name} at activated {activated}: expected {expected} @{cost}, got {got} @{at}"
            ));
        }
    }
    assert!(
        wrongs.is_empty(),
        "{} of {} runs:\n{}",
        wrongs.len(),
        rows.len(),
        wrongs.join("\n")
    );
}


/// placeholder's check, and the tree with its constants substituted reduces
#[test]
fn where_the_second_evaluation_answers_the_first_error_and_counter_stand() {
    let bytes = base16::decode("100148010401010a01d193b173000406").unwrap();
    let tree = from_bytes(&bytes)
        .with_versions(
            ErgoTreeVersion::V3,
            ErgoTreeVersion::V3,
            ErgoTree::sigma_parse,
        )
        .unwrap();
    let lazy_ctx = context(3);
    let lazy = lazy_ctx.with_constants(tree.constants().unwrap());
    let first = tree.root_expr().unwrap().eval(&mut Env::empty(), &lazy);
    assert!(first.is_err());
    let ctx = context(3);
    let reduced = reduce_to_crypto(&tree, &ctx);
    let refusal = reduced.as_ref().err().map(innermost);
    assert!(
        matches!(refusal, Some(EvalError::Misc(text)) if text.starts_with("Unsupported tuple type")),
        "{refusal:?}"
    );
    assert_eq!(ctx.jit_cost_value(), lazy.jit_cost_value());
}

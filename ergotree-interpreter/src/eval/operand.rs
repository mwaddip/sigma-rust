    /// The rows whose error or cost counter is not the table's
    fn wrong_rows(rows: &[Row]) -> alloc::vec::Vec<alloc::string::String> {
        let mut wrong = alloc::vec::Vec::new();
        for (name, body, version, variant, cost) in rows {
            let (res, stopped_at) = eval_body(body, ErgoTreeVersion::from(*version));
            let ok = match &res {
                Err(e) => {
                    alloc::format!("{:?}", innermost(e)).starts_with(variant) && stopped_at == *cost
                }
                Ok(_) => false,
            };
            if !ok {
                wrong.push(alloc::format!(
                    "{name}: expected {variant} at {cost}, got {res:?} at {stopped_at}"
                ));
            }
        }
        wrong
    }


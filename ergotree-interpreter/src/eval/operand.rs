//! An operand of a node, evaluated and cast as sigmastate's `evalTo[C]` casts it.
//!
//! A node's `eval` in sigmastate is a fixed sequence of steps: it evaluates an operand, casts it,
//! adds a cost, runs its body. `Value.evalTo[T]` (`sigma/ast/values.scala:113-117`) casts inside a
//! generic method, where the cast is erased; the cast that counts is the caller's, to the class the
//! caller names, and it happens at that line: before the next operand is evaluated and before the
//! node's cost is added. So a value of another class stops the evaluation there, with the cost
//! counter where it then stands. Where the caller names no concrete class (`evalTo[Any]`, or the
//! node's own type parameter) nothing is cast, and such an operand is evaluated with
//! [`Evaluable::eval`] directly.
//!
//! The class is the KIND of the value and no more: `evalTo[Coll[Byte]]` casts to `Coll`, so any
//! collection passes, and what a node needs of the items (the bytes of a hash's input) is read in
//! its body, after its cost.
use alloc::format;
use ergotree_ir::mir::expr::Expr;
use ergotree_ir::mir::value::Value;

use crate::eval::env::Env;
use crate::eval::Context;
use crate::eval::EvalError;
use crate::eval::Evaluable;

/// The class an operand is cast to where it is evaluated
#[derive(Clone, Copy, Debug)]
pub(crate) enum OperandClass {
    /// `Boolean`: the cast unboxes
    Boolean,
    /// `Long`: the cast unboxes
    Long,
    /// `sigma.GroupElement`
    GroupElement,
    /// `sigma.Box`
    Box,
    /// `sigma.Coll`, whatever its items: a tuple of other than two items is one (`Tuple.value`), a
    /// pair is not
    Coll,
    /// `scala.Option`
    Option,
}

/// Evaluates `expr` and refuses a value that is not of `class`, as `expr.evalTo[C](env)` does
pub(crate) fn eval_to<'ctx>(
    expr: &Expr,
    class: OperandClass,
    env: &mut Env<'ctx>,
    ctx: &Context<'ctx>,
) -> Result<Value<'ctx>, EvalError> {
    let v = expr.eval(env, ctx)?;
    let is_of_class = match class {
        OperandClass::Boolean => matches!(v, Value::Boolean(_)),
        OperandClass::Long => matches!(v, Value::Long(_)),
        OperandClass::GroupElement => matches!(v, Value::GroupElement(_)),
        OperandClass::Box => matches!(v, Value::CBox(_)),
        OperandClass::Coll => matches!(v, Value::Coll(_)),
        OperandClass::Option => matches!(v, Value::Opt(_)),
    };
    if is_of_class {
        Ok(v)
    } else {
        Err(EvalError::UnexpectedValue(format!(
            "an operand of class {class:?} evaluated to {v:?}"
        )))
    }
}

